package com.skillnova.backend.controller;

import com.skillnova.backend.dto.RoadmapGenerationRequest;
import com.skillnova.backend.dto.RoadmapResponse;
import com.skillnova.backend.dto.RoadmapSummaryResponse;
import com.skillnova.backend.entity.User;
import com.skillnova.backend.service.RoadmapService;
import jakarta.validation.Valid;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import java.util.List;
import java.util.UUID;

/**
 * AI-powered roadmap generation and retrieval. All routes require a valid
 * JWT ({@code JwtAuthenticationFilter} populates
 * {@code @AuthenticationPrincipal User}); roadmap reads are scoped to the
 * authenticated user's own roadmaps (see {@code RoadmapRepository}).
 */
@RestController
@RequestMapping("/api/roadmap")
public class RoadmapController {

    private final RoadmapService roadmapService;

    public RoadmapController(RoadmapService roadmapService) {
        this.roadmapService = roadmapService;
    }

    /**
     * Request body is optional - omit it entirely to generate purely from
     * the stored profile, or include any subset of fields to override it
     * for this one generation without changing the stored profile.
     * Persists the generated roadmap (Phase 9) and returns 201 Created.
     */
    @PostMapping("/generate")
    public ResponseEntity<RoadmapResponse> generate(
            @AuthenticationPrincipal User user,
            @Valid @RequestBody(required = false) RoadmapGenerationRequest request
    ) {
        RoadmapGenerationRequest effectiveRequest = request != null ? request : RoadmapGenerationRequest.EMPTY;
        RoadmapResponse response = roadmapService.generateRoadmap(user.getId(), effectiveRequest);
        return ResponseEntity.status(HttpStatus.CREATED).body(response);
    }

    /** Lists all roadmaps previously generated by the authenticated user, newest first. */
    @GetMapping
    public ResponseEntity<List<RoadmapSummaryResponse>> list(@AuthenticationPrincipal User user) {
        return ResponseEntity.ok(roadmapService.listRoadmaps(user.getId()));
    }

    /** Fetches full roadmap detail by ID; 404 if it doesn't exist or isn't owned by this user. */
    @GetMapping("/{id}")
    public ResponseEntity<RoadmapResponse> get(
            @AuthenticationPrincipal User user,
            @PathVariable UUID id
    ) {
        return ResponseEntity.ok(roadmapService.getRoadmap(user.getId(), id));
    }
}
